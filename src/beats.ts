export const f = (sec: number) => Math.round(sec * FPS);

export const BEAT_FRAMES = BEATS.map(f);
export const HIT_FRAMES = HITS.map(f);
export const STRONG_FRAMES = STRONG.map(f);

/** 返回 frame 之前最近的一拍（帧）与距离 */
export const prevBeat = (frame: number) => {
  let lo = 0;
  let hi = BEAT_FRAMES.length - 1;
  if (frame < BEAT_FRAMES[0]) return { index: -1, frame: BEAT_FRAMES[0], delta: 999 };
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (BEAT_FRAMES[mid] <= frame) lo = mid;
    else hi = mid - 1;
  }
  return { index: lo, frame: BEAT_FRAMES[lo], delta: frame - BEAT_FRAMES[lo] };
};

/** 拍点脉冲包络：刚过拍子时接近 1，随后衰减到 0 */
export const beatPulse = (frame: number, decay = 7) => {
  const { delta } = prevBeat(frame);
  if (delta > 60) return 0;
  return Math.exp(-delta / decay);
};

/** 小节脉冲：每 4 拍一次强脉冲 */
export const barPulse = (frame: number, decay = 9) => {
  const { index } = prevBeat(frame);
  if (index < 0) return 0;
  const bi = index % 4;
  if (bi !== 0) return 0;
  const { delta } = prevBeat(frame);
  if (delta > 60) return 0;
  return Math.exp(-delta / decay);
};

/** 最近一次超级卡点的强度包络 */
export const hitPulse = (frame: number, decay = 5) => {
  let best = 0;
  for (const hf of HIT_FRAMES) {
    const d = frame - hf;
    if (d >= 0 && d < 40) best = Math.max(best, Math.exp(-d / decay));
  }
  return best;
};
